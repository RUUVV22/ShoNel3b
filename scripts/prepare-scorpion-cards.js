// Generates static Metro require() statements for Scorpion Night artwork.
// Run whenever card images are replaced/added in the existing source directory.
// A missing image stays explicitly absent; never swap in a different role's art.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname,'..');
const folder = path.join(root,'assets','scurbion nights assets');
const dest = path.join(root,'mobile','constants','scorpionRoleSources.js');
const entries = {
  MIMIC:'01-muqallid.png',
  SCORPION:'02-aqrab.png',
  SCORPIONESS:'03-aqraba.png',
  MINION:'04-musaed.png',
  MASON:'05-sahab-1.png',
  MASON_2:'06-sahab-2.png',
  SEER:'07-arrafa.png',
  ROBBER:'08-harami.png',
  TROUBLEMAKER:'09-qallab.png',
  DRUNK:'10-sakran.png',
  INSOMNIAC:'11-bint-alleil.png',
  VILLAGER:'12-muwatin-1.png',
  // The three villager cards intentionally share VILLAGER art (12-muwatin-1.png).
  HUNTER:'15-fazza.png',
  TANNER:'16-kabsh-alfida.png',
};
const lines = ['// Generated by node scripts/prepare-scorpion-cards.js.',
  'export const SCORPION_IMAGE_SOURCES = Object.freeze({'];
const missing=[];
for(const [id,name] of Object.entries(entries)) {
  if(fs.existsSync(path.join(folder,name)))
    lines.push(`  ${id}: require('../../assets/scurbion nights assets/${name}'),`);
  else missing.push(name);
}
lines.push('});');
lines.push('export const MISSING_SCORPION_CARD_ART = Object.freeze('+JSON.stringify(missing)+');');
fs.writeFileSync(dest,lines.join('\n')+'\n');
console.log('Scorpion artwork sources refreshed. Missing: '+(missing.join(', ')||'none'));
