// Generate Metro-compatible static require() maps for audio files present on disk.
// This is run by npm run scorpion:audio:prepare and npm run build:web.
// No private ElevenLabs credentials or signed download links ship in the app.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');

const sfxIds = [
  'shuffle_cards','deal_card','flip_card','courtyard_ambience',
  'replace_card','select_card','deselect_card','night_bell',
  'role_wake','role_sleep','secret_look','dawn_transition',
  'timer_warning','vote_select','vote_confirm','results_reveal',
  'win_sting','lose_sting','button_click',
];
const copyRoles = [
  'mimic','minion','mason','seer','robber','troublemaker','drunk',
  'insomniac','scorpion','scorpioness','villager','hunter','tanner',
];
function writeSources(folder, destination, ids, aliases = {}) {
  fs.mkdirSync(path.join(root, folder), { recursive: true });
  const found = [];
  const requires = [];
  for (const id of ids) {
    const filename = aliases[id] || id;
    const file = path.join(root, folder, filename + '.mp3');
    if (!fs.existsSync(file)) continue;
    found.push(id);
    requires.push(`  ${id}: require('../../${folder}/${filename}.mp3'),`);
  }
  fs.writeFileSync(path.join(root, 'mobile', 'constants', destination),
    [
      '// Generated by node scripts/prepare-scorpion-audio.js. Do not edit by hand.',
      `export const ${destination === 'scorpionAudioSources.js' ? 'SCORPION_AUDIO_SOURCES' : 'SCORPION_NARRATION_SOURCES'} = Object.freeze({`,
      ...requires, '});', ''
    ].join('\n')
  );
  console.log(`${destination}: ${found.length} loaded; ${ids.length - found.length} missing`);
  if (ids.length !== found.length) console.log('Missing:', ids.filter(x => !found.includes(x)).join(', '));
}

const soundFolder = 'assets/scorpion-sfx';
writeSources(soundFolder, 'scorpionAudioSources.js', sfxIds);

const voiceFolder = 'assets/scorpion-narration';
const voiceFiles = fs.existsSync(path.join(root, voiceFolder))
  ? fs.readdirSync(path.join(root, voiceFolder)).filter(file => /^[a-z0-9_]+\.mp3$/.test(file)).map(file => file.slice(0, -4)).sort()
  : [];
const aliases = {};
for (const role of copyRoles) aliases[`copied_${role}_close`] = 'copycat_close';
writeSources(voiceFolder, 'scorpionNarrationSources.js',
  [...new Set([...voiceFiles, ...Object.keys(aliases)])], aliases);
